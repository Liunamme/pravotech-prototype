/**
 * Токенизация текста для потокового вывода (docs/SCENARIOS.md, §5.4).
 *
 * По словам, с сохранением пробелов и переносов строк — не по символам
 * (посимвольно выглядит неестественно медленно). Инвариант, который обязан
 * выполняться всегда: `tokenize(text).join('') === text`.
 */

/**
 * Разбивает текст на чередующиеся отрезки «непробельные символы» и
 * «пробельные символы» (включая `\n`). Альтернация `\s+|\S+` без флага `g`
 * пропусков не оставляет — каждый символ входной строки попадает ровно
 * в один токен, поэтому склейка результата всегда даёт исходную строку.
 */
export function tokenize(text: string): string[] {
  if (text.length === 0) return [];
  return text.match(/\s+|\S+/g) ?? [];
}
