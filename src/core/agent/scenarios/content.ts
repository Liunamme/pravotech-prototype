export function fallbackWithContext(topicLabel: string): string {
  return (
    `Готового сценария для этого запроса в демо нет, но вот что нашёл по теме «${topicLabel}» — ` +
    'открыл источник ниже. Если уточните вопрос, посмотрю внимательнее.'
  );
}

export function fallbackGeneric(workspaceLabel: string): string {
  return (
    `Не нашёл в этом запросе ничего, за что можно зацепиться предметно. В пространстве «${workspaceLabel}» ` +
    'я умею проверять автопролонгации по договорам, готовить позицию к заседанию и разбирать письма ' +
    'контрагентов о цене — сформулируйте запрос ближе к одной из этих задач, и я отвечу по существу.'
  );
}
