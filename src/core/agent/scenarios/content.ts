export function casePositionResult(d: { hearingDay: string }): string {
  return (
    'Позиция по делу №А40-118742/2026 готова. Ответчик ссылается на пропуск срока исковой давности' +
    ' — довод не подтверждается: по п. 14 Обзора практики ВС РФ №2 (2024) срок начинает течь со дня,' +
    ' следующего за днём, когда обязательство должно было быть исполнено, а не с момента иных действий сторон.\n\n' +
    'Второй довод ответчика — о несоответствии качества товара — опровергается заключением эксперта:' +
    ' выявленные отклонения признаны несущественными и не препятствующими использованию товара по назначению.\n\n' +
    `Проект возражений на отзыв готов. Прошу подтвердить позицию к заседанию ${d.hearingDay}.`
  );
}

